from docai.evals.runner import RUNS_DIR

RESULTS_PATH = Path(__file__).resolve().parents[5] / "docs" / "RESULTS.md"
SECURITY_RUNS = RUNS_DIR.parent / "security" / "runs"  # docai.evals.injection
TYPES = (
    "single_fact",
    "table",
    "image",
    "cross_doc",
    "aggregate",
    "cross_lingual",
    "unanswerable",
)
HEADER = """# Results

Generated by `docai evals report` from the recorded runs in `services/ai/evals/runs/`.
Do not edit by hand. Protocol and metric definitions:
[Evaluation methodology](../services/ai/README.md#evaluation-methodology).

Accuracy is the share of golden questions answered correctly: rules first (numbers,
dates, yes/no, refusals, accepted text forms), then the LLM judge for the rest.
Cost per query uses Gemini paid-tier prices from `services/ai/src/docai/core/prices.py`.
V0 is the baseline (single-document chat over the first 8,000 characters of the right
document); A1 rows are the chat graph over the whole library. Latency is shown
only where every model call was made during the run, not replayed from the cache.
"""

EXTRACTION_HEADER = """
## Extraction

Fields from the ingestion pipeline (Docling or OCR text plus figure captions, then one
structured call per document), scored against ground truth. Synthetic invoices,
receipts and contracts are scored on every field; SROIE receipts on merchant, date and
total, its human labels. F1 is micro-averaged over fields; a field that is empty in
both the truth and the extraction (such as no paid stamp) doesn't count. Model cost is
what processing the documents cost, including calls served from the cache.

Category accuracy compares with the corpus labels. Every synthetic document gets the
right category. SROIE labels all its documents receipts, but 9 of its 60 are bakery
delivery invoices to businesses, which the pipeline files as invoices; they and 4
debatable cash bills are the category misses.
"""


RETRIEVAL_HEADER = """
## Retrieval

All 200 corpus documents are indexed under one tenant, so every document is a
distractor for every question. A retrieved chunk is a hit when it comes from a labelled
document and covers the labelled page, if the label names one. Recall@k is the share of
a question's labelled (document, page) items in the top k; MRR@10 scores the first hit;
nDCG@10 gains for each hit that finds a labelled item not found above it; document
recall@10 ignores pages. Questions without a relevant document are skipped.

Latency is per query on the development machine (M2, 8 GB; TEI on CPU in Docker): query
embedding, Qdrant search and, where used, reranking 50 candidates (20 in the `-20`
variants). Index cost is what indexing the 200 documents costs from scratch at list
prices: Gemini contexts (Gemini's implicit prefix cache took about 20% off in a sample)
or Gemini embeddings; TEI models are free. With 71 questions, differences of 0.01 to
0.02 are one or two questions, and tied reciprocal-rank-fusion scores can come back in
a different order after a rebuild. `-nr` variants don't rerank. The default pipeline is
V5-nr; see [Key decisions](ARCHITECTURE.md#key-decisions).
"""
